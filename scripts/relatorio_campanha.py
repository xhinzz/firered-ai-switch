"""Gera docs/campanha.md a partir da memória da campanha (memoria/estado.json e memoria/eventos.jsonl).

A memória é o diário que a própria IA grava enquanto joga; os textos dos marcos e das capturas são dela (em português).
Uso: python scripts/relatorio_campanha.py
"""

import json
import sys
from collections import Counter
from datetime import datetime
from pathlib import Path

RAIZ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(RAIZ))

from fireredia import caminhos  # noqa: E402

ANO = 2026  # o diário grava "dd/mm hh:mm:ss"


def _data(t):
    return datetime.strptime(f"{t} {ANO}", "%d/%m %H:%M:%S %Y")


def _linha(*celulas):
    return "| " + " | ".join(str(c).replace("|", "/").replace("\n", " ") for c in celulas) + " |"


def gerar():
    estado = json.loads((caminhos.MEMORIA / "estado.json").read_text(encoding="utf-8"))
    eventos = [json.loads(linha) for linha in (caminhos.MEMORIA / "eventos.jsonl").open(encoding="utf-8")]
    tipos = Counter(e.get("tipo") for e in eventos)
    papeis = Counter(
        "estrategista" if "estrategista" in e["texto"] else "executor" for e in eventos if e.get("tipo") == "episodio"
    )
    modelos = sorted({e["texto"].split(", ")[-1].rstrip(")") for e in eventos if e.get("tipo") == "episodio"})
    inicio, fim = _data(eventos[0]["t"]), _data(eventos[-1]["t"])
    c = estado.get("contadores", {})

    out = [
        "# Campaign log",
        "",
        "Generated by `scripts/relatorio_campanha.py` from the agent's own memory (`memoria/`, not versioned).",
        "Milestone and capture descriptions are quoted as the agent wrote them (Portuguese).",
        "",
        "## Numbers",
        "",
        "| | |",
        "|---|---|",
        _linha("Period", f"{inicio:%Y-%m-%d %H:%M} → {fim:%Y-%m-%d %H:%M}"),
        _linha("In-game time", estado.get("tempo_jogo", "?")),
        _linha(
            "Episodes",
            f"{papeis['estrategista'] + papeis['executor']} "
            f"({papeis['estrategista']} strategist, {papeis['executor']} executor)",
        ),
        _linha("Models", ", ".join(f"`{m}`" for m in modelos)),
        _linha("Tool actions", tipos["acao"]),
        _linha("Decisions logged by the model", tipos["decisao"]),
        _linha("Battles finished / won", f"{c.get('batalhas_terminadas', '?')} / {c.get('vitorias', '?')}"),
        _linha("Training battles (autopilot)", c.get("batalhas_treino", "?")),
        _linha("Wild Pokémon caught", f"{c.get('capturas', '?')} ({c.get('bolas_usadas', '?')} balls thrown)"),
        _linha("Badges", f"{len(estado.get('insignias', []))}/8"),
        _linha("API cost", f"US$ {estado.get('custo_usd', 0):.2f}"),
        "",
        "## Story milestones",
        "",
        _linha("When", "Milestone", "Agent's note"),
        "|---|---|---|",
    ]
    for marco, info in estado.get("marcos", {}).items():
        out.append(_linha(info.get("quando", ""), f"`{marco}`", info.get("resultado", "")))
    out += ["", "## Captures", "", _linha("When", "Episode", "Agent's note"), "|---|---|---|"]
    for e in eventos:
        if e.get("tipo") == "captura":
            out.append(_linha(e["t"], e.get("ep", ""), e["texto"]))
    destino = RAIZ / "docs" / "campanha.md"
    destino.write_text("\n".join(out) + "\n", encoding="utf-8")
    return destino


if __name__ == "__main__":
    print(gerar())
